// Helper to generate concrete Session 1, Session 2 ... for drill-down inspection
export const getSessionsForPurchase = (purchase: PTPurchaseRecord): TrainingSessionDetail[] => {
  const result: TrainingSessionDetail[] = [];
  const pDate = new Date(purchase.date + 'T09:00:00');
  
  const topics = [
    'Screening, FMS & Postural Assessment',
    'Core Activation & Basic Movement Pattern',
    'Hypertrophy: Chest, Triceps & Upper Push',
    'Hypertrophy: Back, Biceps & Pull Strength',
    'Lower Body: Squat Mechanics & Quad Focus',
    'Lower Body: Deadlift & Posterior Chain',
    'Metabolic Conditioning & Core Stability',
    'Push Progression & Shoulder Mobility',
    'Pull Strength & Latissimus Dorsi Focus',
    'Glute Hypertrophy & Hamstring Isolation',
    'Unilateral Strength & Dynamic Balance',
    'Tempo Training & Time Under Tension',
    'Progressive Overload Test & Benchmarks',
    'HIIT Conditioning & VO2 Max Endurance',
    'Full Body Functional Circuit',
    'Deload & Active Recovery Mobility',
    'Chest Peak Contraction & Cable Mechanics',
    'Olympic Lift Intro: Power Clean Mechanics',
    'Explosive Power & Plyometrics',
    'Core Anti-Rotation & Farmers Walk Carry',
    'Body Composition Evaluation & Milestone',
    'High Volume Upper Pump Routine',
    'Hamstring Leg Curl & Romanian Deadlift',
    'Overhead Press & Tricep Finisher',
    'Barbell Row & Bicep Peak Volume',
    'Leg Press Heavy & Walking Lunges',
    'Cardiovascular Capacity & Sled Pushes',
    'Kettlebell Swings & Turkish Get-Up',
    'Final Body Measurement & Re-Screening',
    'Graduation Workout & Next Goal Setting'
  ];

  for (let i = 1; i <= purchase.totalSessions; i++) {
    // Generate date incremented by 3 to 4 days
    const sessDate = new Date(pDate);
    sessDate.setDate(sessDate.getDate() + (i * 3));
    const dateStr = sessDate.toISOString().split('T')[0];
    const isCompleted = i <= purchase.completedSessions;
    
    result.push({
      sessionId: `SESS-${purchase.id}-${String(i).padStart(2, '0')}`,
      sessionNumber: i,
      date: dateStr,
      time: i % 2 === 0 ? '16:00 WIB' : '09:00 WIB',
      status: isCompleted ? 'Selesai' : (i === purchase.completedSessions + 1 ? 'Menunggu' : 'Menunggu'),
      note: topics[(i - 1) % topics.length],
      valStaf: isCompleted,
      valTrainer: isCompleted,
      valMember: isCompleted
    });
  }

  return result;
};

